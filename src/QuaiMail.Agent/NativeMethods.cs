using System.Runtime.InteropServices;

namespace QuaiMail.Agent;

/// <summary>
/// Les quelques fonctions de Windows dont l'agent a besoin (fenêtre cachée, icône de la zone de notification, menu,
/// mémoire). Déclarations écrites à la main avec <c>LibraryImport</c> (générées à la compilation, compatibles Native
/// AOT), comme <c>NativeMethods.cs</c> de Quai Mail : voir docs/DECISIONS.md.
/// </summary>
internal static unsafe partial class NativeMethods
{
