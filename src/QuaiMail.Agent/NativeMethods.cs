    [return: MarshalAs(UnmanagedType.Bool)]
    public static partial bool SetProcessWorkingSetSizeEx(nint process, nint minimum, nint maximum, uint flags);

    public static ushort LowWord(nint value) => (ushort)((nuint)value & 0xFFFF);

    public static short SignedLowWord(nint value) => (short)((nuint)value & 0xFFFF);

    public static short SignedHighWord(nint value) => (short)(((nuint)value >> 16) & 0xFFFF);
}
